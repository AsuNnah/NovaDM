'use strict';
// Builds src/ui/preload-toolbar.gen.js: the UI preload with electron-chrome-extensions' browser-action module
// joined in. A sandboxed preload can only require('electron'), so the toolbar (sandbox: true) can't load the
// module from node_modules; the module itself needs nothing but 'electron'. Run by `postinstall`, so every
// `npm ci` (and a Dependabot bump of the package) rebuilds it. The output is git-ignored.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const NEEDLE = "require('electron-chrome-extensions/browser-action')";

function build() {
  const preload = fs.readFileSync(path.join(root, 'src', 'ui', 'preload-ui.js'), 'utf8');
  if (!preload.includes(NEEDLE)) throw new Error(`preload-ui.js no longer contains ${NEEDLE}`);
  const modPath = require.resolve('electron-chrome-extensions/browser-action', { paths: [root] });
  const mod = fs.readFileSync(modPath, 'utf8');
  // Any require other than 'electron' would fail in the sandbox: refuse to build rather than ship a broken toolbar.
  const others = [...mod.matchAll(/require\(\s*["']([^"']+)["']\s*\)/g)].map((m) => m[1]).filter((n) => n !== 'electron');
  if (others.length) throw new Error(`browser-action now requires ${[...new Set(others)].join(', ')}: it can't run in a sandboxed preload`);
  const wrapped = `(function () { const module = { exports: {} }; const exports = module.exports;\n${mod}\nreturn module.exports; })()`;
  const out = '// Generated by tools/build-ui-preload.js from src/ui/preload-ui.js and electron-chrome-extensions/browser-action.\n'
    + '// Do not edit; run `node tools/build-ui-preload.js` (npm runs it after install).\n'
    + preload.replace(NEEDLE, wrapped);
  const file = path.join(root, 'src', 'ui', 'preload-toolbar.gen.js');
  fs.writeFileSync(file, out);
  return file;
}

if (require.main === module) console.log('built ' + path.relative(root, build()));
module.exports = { build };
